// npm run rl:train: trains the viewpoint policy and writes lib/autonomy/nav-weights.ts with its held-out scores.
import { writeFileSync } from "node:fs";
import { NavTrainer } from "../lib/autonomy/nav";
import { NAV_WEIGHTS } from "../lib/autonomy/nav-weights";
import { TEST_BASE, scoreStrategy } from "../lib/autonomy/nav-eval";
import type { StrategyId } from "../lib/gantry/strategies";

const EPISODES = 1000;
const SEED = 1;
const LAYOUTS = 120;
const t = new NavTrainer({ episodes: EPISODES, seed: SEED });
t.step(EPISODES);
const weights = t.weights.map((w) => Math.round(w * 1e4) / 1e4);
NAV_WEIGHTS.splice(0, NAV_WEIGHTS.length, ...weights);
const ids: StrategyId[] = ["learned", "detection-driven", "serpentine", "uncertainty", "coverage"];
const heldOut = ids.map((strategy) => ({ strategy, scores: scoreStrategy(strategy, TEST_BASE, LAYOUTS) }));
const round = (_: string, v: unknown) => (typeof v === "number" ? Math.round(v * 1e4) / 1e4 : v);
const bins = 25;
const curve = Array.from({ length: bins }, (_, b) => {
  const part = t.curve.slice((b * EPISODES) / bins, ((b + 1) * EPISODES) / bins);
  return part.reduce((s, c) => s + c.reward, 0) / part.length;
});
writeFileSync(
  new URL("../lib/autonomy/nav-weights.ts", import.meta.url),
  `// Generated by \`npm run rl:train\`. Do not edit: retrain instead.
import type { EnvironmentId } from "../sim/environments";
import type { StrategyId } from "../gantry/strategies";
import type { NavScore } from "./nav-eval";

export const NAV_WEIGHTS: number[] = ${JSON.stringify(weights)};
export const NAV_TRAINING: { seed: number; episodes: number; layouts: number; curve: number[] } = ${JSON.stringify({ seed: SEED, episodes: EPISODES, layouts: LAYOUTS, curve }, round)};
/** Means over ${LAYOUTS} held-out layouts in the real engine (seeds never used for training or choices). */
export const NAV_HELD_OUT: { strategy: StrategyId; scores: Record<"all" | EnvironmentId, NavScore> }[] = ${JSON.stringify(heldOut, round, 1)};
`,
);
for (const h of heldOut) console.log(h.strategy.padEnd(18), Object.entries(h.scores).map(([k, v]) => `${k} ${v.found.toFixed(2)}/${v.correct.toFixed(2)}/${v.scanS.toFixed(1)}s/${v.score.toFixed(2)}`).join("  "));
